#!/usr/bin/env python3
"""Generate web/server.css from the gen/*.py modules (Python 3 stdlib only).

Every module exposes  rules() -> str  and  properties() -> [(name, syntax, inherits, initial)];
optionally  weak_properties()  = registrations of props that OTHER modules produce but this one reads (fallback only:
used when no module registers the name, e.g. --au while gen/auth.py does not exist; a producer's registration wins).
build.py registers each property once (identical duplicates are merged, conflicting ones are an error), then emits
    @property rules, the modules' rules, the error-message table on :root, and the hidden container #c.
Modules: route (R), auth (A/S/O, optional until it exists), body (B), verdict (V), stage3 (D, r), templates (response templates as registered strings).
"""
import importlib
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)

MODULES = ['route', 'auth', 'body', 'verdict', 'stage3', 'templates', 'http']
OPTIONAL = {'auth'}          # built without it until it exists: --au stays at its initial 0 (missing bearer)

MESSAGES = [
    'not found', 'invalid post id', 'post not found', 'missing bearer token', 'invalid or expired token',
    'invalid token payload', 'malformed JSON body', 'body is required', 'body must be at most 500 characters',
    'internal server error',
]


def norm(p):
    name, syntax, inherits, initial = p
    if not name.startswith('--'):
        name = '--' + name
    if '<' not in syntax and syntax != '*':
        syntax = '<%s>' % syntax
    return name, syntax, bool(inherits), str(initial)


def build(modules=None, dest=None, messages=True):
    modules = modules or MODULES
    props = {}
    weak = {}
    owner = {}
    chunks = []
    used = []
    for m in modules:
        path = os.path.join(HERE, m + '.py')
        if not os.path.exists(path):
            if m in OPTIONAL and modules is MODULES:
                print('build: gen/%s.py not found, building without it' % m, file=sys.stderr)
                continue
            raise SystemExit('build: missing gen/%s.py' % m)
        mod = importlib.import_module(m)
        used.append(m)
        for p in mod.properties():
            name, syntax, inherits, initial = norm(p)
            old = props.get(name)
            if old is not None and old != (syntax, inherits, initial):
                raise SystemExit('build: conflicting registrations of %s: %s %r (%s) vs %s %r (%s)'
                                 % (name, owner[name], old, 'first', m, (syntax, inherits, initial), 'second'))
            props[name] = (syntax, inherits, initial)
            owner.setdefault(name, m)
        for p in getattr(mod, 'weak_properties', lambda: [])():
            weak.setdefault(norm(p)[0], norm(p)[1:])
        chunks.append((m, mod.rules()))
    for n, v in weak.items():
        props.setdefault(n, v)
    out = ['/* generated by gen/build.py: do not edit. modules: %s */\n' % ', '.join(used)]
    out.append(''.join('@property %s{syntax:"%s";inherits:%s;initial-value:%s}\n'
                       % (n, s, 'true' if i else 'false', v) for n, (s, i, v) in sorted(props.items())))
    out.append('#c{display:none}\n')
    if messages:
        out.append(':root{%s}\n' % ''.join('--msg-%d:"%s";' % (i, m) for i, m in enumerate(MESSAGES)))
    for m, r in chunks:
        out.append('/* %s */\n%s' % (m, r))
    css = ''.join(out)
    dest = dest or os.path.join(HERE, '..', 'web', 'server.css')
    with open(dest, 'w') as f:
        f.write(css)
    print('build: wrote %s (%d bytes, %d properties, modules %s)' % (os.path.relpath(dest, os.path.join(HERE, '..')), len(css),
                                                                      len(props), ', '.join(used)), file=sys.stderr)
    return css


if __name__ == '__main__':
    # python3 gen/build.py [--modules route,body] [--out file]   (the options are for the unit tests)
    a = sys.argv[1:]
    opt = {a[i]: a[i + 1] for i in range(0, len(a) - 1, 2)}
    build(opt['--modules'].split(',') if '--modules' in opt else None, opt.get('--out'))
